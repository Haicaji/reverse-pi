#!/usr/bin/env bash

# Shared configuration and helpers for the delamain Skill.
#
# delamain is deployed as a single Docker container. All persistent state lives
# under <repo>/tools/delamain so it can be inspected and removed independently
# of the host system.

set -euo pipefail

_config_script_dir="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd -P)"
REPO_ROOT="$(cd "${_config_script_dir}/../../../.." && pwd -P)"
SKILL_DIR="$(cd "${_config_script_dir}/.." && pwd -P)"

DEFAULT_IMAGE_REPO="ghcr.io/xjoker/delamain"
DEFAULT_IMAGE_TAG="latest"
DEFAULT_IMAGE="${DEFAULT_IMAGE_REPO}:${DEFAULT_IMAGE_TAG}"
DEFAULT_PORT="8651"
DEFAULT_APK_DIR="${REPO_ROOT}/workdir/apks"
DEFAULT_STATE_DIR="${REPO_ROOT}/tools/delamain"
CONTAINER_NAME="reverse-pi-delamain"
COMPOSE_PROJECT="reverse-pi-delamain"

# Capture caller overrides before loading the generated .env so an explicit
# environment variable always wins over the persisted value.
_override_port="${DELAMAIN_PORT:-}"
_override_apk_dir="${DELAMAIN_APK_DIR:-}"
_override_image="${DELAMAIN_IMAGE:-}"
_override_transfer_max_mb="${DELAMAIN_TRANSFER_MAX_MB:-}"
_override_cache_max_gb="${DELAMAIN_CACHE_MAX_GB:-}"
_override_auth_file="${DELAMAIN_AUTH_FILE:-}"
_override_state_dir="${DELAMAIN_STATE_DIR:-}"

STATE_DIR="${_override_state_dir:-${DEFAULT_STATE_DIR}}"
ENV_FILE="${STATE_DIR}/.env"
COMPOSE_FILE="${STATE_DIR}/compose.yml"
BACKUP_DIR="${STATE_DIR}/backups"
LOG_DIR="${STATE_DIR}/logs"

_persisted_image=""
if [[ -f "${ENV_FILE}" ]]; then
    # Generated by install-delamain.sh. It contains only simple KEY="value"
    # assignments (hex token, absolute paths, image reference, integers).
    # shellcheck disable=SC1090
    source "${ENV_FILE}"
    _persisted_image="${DELAMAIN_IMAGE:-}"
fi

PORT="${_override_port:-${DELAMAIN_PORT:-${DEFAULT_PORT}}}"
APK_DIR="${_override_apk_dir:-${DELAMAIN_APK_DIR:-${DEFAULT_APK_DIR}}}"
IMAGE="${_override_image:-${_persisted_image:-${DEFAULT_IMAGE}}}"

# Legacy installs stored a digest pin in .env. Follow the floating upstream tag
# again, unless the caller explicitly overrides DELAMAIN_IMAGE.
IMAGE_MIGRATED_FROM=""
if [[ -z "${_override_image}" && "${_persisted_image}" == *"@"* && "${_persisted_image%%@*}" == "${DEFAULT_IMAGE_REPO}" ]]; then
    IMAGE_MIGRATED_FROM="${_persisted_image}"
    IMAGE="${DEFAULT_IMAGE}"
fi
TRANSFER_MAX_MB="${_override_transfer_max_mb:-${JADX_TRANSFER_MAX_MB:-1024}}"
CACHE_MAX_GB="${_override_cache_max_gb:-${JADX_CACHE_MAX_GB:-50}}"
TOKEN="${DELAMAIN_AUTH_TOKENS:-}"

SECRETS_DIR="${REPO_ROOT}/.pi/secrets"
AUTH_FILE="${_override_auth_file:-${DELAMAIN_AUTH_FILE:-${SECRETS_DIR}/delamain.auth}}"

MCP_URL="http://127.0.0.1:${PORT}/mcp"
HEALTH_URL="http://127.0.0.1:${PORT}/health"

if ! [[ "${PORT}" =~ ^[0-9]+$ ]] || ((PORT < 1 || PORT > 65535)); then
    echo "Error: invalid delamain port: ${PORT}" >&2
    exit 1
fi

log() {
    printf '[delamain] %s\n' "$*"
}

warn() {
    printf '[delamain] WARNING: %s\n' "$*" >&2
}

die() {
    printf '[delamain] ERROR: %s\n' "$*" >&2
    exit 1
}

print_docker_fix() {
    cat >&2 <<'EOF'
Docker is installed but the current user cannot access the daemon (or the CLI
is missing). Pi never calls sudo. Fix this once, then restart the Pi session:

    sudo usermod -aG docker "$USER"

Log out and back in (or reboot) so the new group membership takes effect, then
fully restart the editor/terminal hosting Pi (restarting only the Pi session
may keep the old supplementary groups). Verify with:

    docker info

If Docker is not installed, install Docker Engine + Compose from your package
manager first; this Skill does not modify system packages.
EOF
}

require_commands() {
    local missing=() cmd
    for cmd in docker curl jq ss; do
        if ! command -v "${cmd}" >/dev/null 2>&1; then
            missing+=("${cmd}")
        fi
    done
    if ((${#missing[@]} > 0)); then
        printf 'DELAMAIN_PREREQUISITE_MISSING: missing command(s): %s\n' "${missing[*]}" >&2
        return 1
    fi
    if ! docker compose version >/dev/null 2>&1; then
        echo "DELAMAIN_PREREQUISITE_MISSING: docker compose is not available." >&2
        return 1
    fi
    return 0
}

docker_ok() {
    if ! command -v docker >/dev/null 2>&1; then
        echo "DELAMAIN_DOCKER_UNAVAILABLE: docker CLI not found." >&2
        print_docker_fix
        return 10
    fi
    if ! docker info >/dev/null 2>&1; then
        echo "DELAMAIN_DOCKER_UNAVAILABLE: cannot access the Docker daemon." >&2
        docker info 2>&1 | head -n 3 >&2 || true
        print_docker_fix
        return 10
    fi
    return 0
}

compose() {
    # Pass the resolved values explicitly: an inherited or sourced variable
    # would otherwise take precedence over the generated .env file, so image
    # migrations and runtime overrides would not reach Compose.
    env \
        DELAMAIN_IMAGE="${IMAGE}" \
        DELAMAIN_PORT="${PORT}" \
        DELAMAIN_APK_DIR="${APK_DIR}" \
        DELAMAIN_STATE_DIR="${STATE_DIR}" \
        DELAMAIN_AUTH_TOKENS="${TOKEN}" \
        JADX_TRANSFER_MAX_MB="${TRANSFER_MAX_MB}" \
        JADX_CACHE_MAX_GB="${CACHE_MAX_GB}" \
        docker compose \
        --project-name "${COMPOSE_PROJECT}" \
        --project-directory "${STATE_DIR}" \
        --env-file "${ENV_FILE}" \
        -f "${COMPOSE_FILE}" \
        "$@"
}

require_installed() {
    if [[ ! -f "${COMPOSE_FILE}" || ! -f "${ENV_FILE}" ]]; then
        echo "DELAMAIN_NOT_INSTALLED: run scripts/install-delamain.sh first." >&2
        return 1
    fi
    return 0
}

port_in_use() {
    ss -ltnH 2>/dev/null | awk '{print $4}' | grep -qE "[:.]${PORT}$"
}

our_container_running() {
    [[ "$(docker inspect -f '{{.State.Running}}' "${CONTAINER_NAME}" 2>/dev/null || true)" == "true" ]]
}

generate_token() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex 32
    else
        od -An -N32 -tx1 /dev/urandom | tr -d ' \n'
    fi
}

write_env_file() {
    mkdir -p "${STATE_DIR}"
    chmod 700 "${STATE_DIR}"
    (
        umask 077
        cat >"${ENV_FILE}" <<EOF
DELAMAIN_IMAGE="${IMAGE}"
DELAMAIN_PORT="${PORT}"
DELAMAIN_APK_DIR="${APK_DIR}"
DELAMAIN_STATE_DIR="${STATE_DIR}"
DELAMAIN_AUTH_TOKENS="${TOKEN}"
JADX_TRANSFER_MAX_MB="${TRANSFER_MAX_MB}"
JADX_CACHE_MAX_GB="${CACHE_MAX_GB}"
EOF
    )
    chmod 600 "${ENV_FILE}"
}

write_auth_file() {
    mkdir -p "${SECRETS_DIR}"
    chmod 700 "${SECRETS_DIR}"
    (
        umask 077
        printf 'Bearer %s' "${TOKEN}" >"${AUTH_FILE}"
    )
    chmod 600 "${AUTH_FILE}"
}

read_token_from_auth_file() {
    if [[ -r "${AUTH_FILE}" ]]; then
        sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^Bearer[[:space:]]\+//' "${AUTH_FILE}"
    fi
}

http_code() {
    local url="$1"
    shift
    local code
    code="$(curl -sS -o /dev/null -w '%{http_code}' --max-time 10 "$@" "${url}" 2>/dev/null || true)"
    printf '%s' "${code:-000}"
}

health_payload() {
    curl -fsS --max-time 5 "${HEALTH_URL}" 2>/dev/null || true
}

wait_for_health() {
    local timeout="${1:-180}" elapsed=0 payload
    while ((elapsed < timeout)); do
        payload="$(health_payload)"
        if [[ -n "${payload}" ]] && printf '%s' "${payload}" | jq -e '.status == "healthy"' >/dev/null 2>&1; then
            printf '%s' "${payload}"
            return 0
        fi
        sleep 2
        elapsed=$((elapsed + 2))
    done
    return 1
}

_extract_mcp_json() {
    local file="$1"
    if jq -e . "${file}" >/dev/null 2>&1; then
        cat "${file}"
        return 0
    fi
    # Streamable HTTP may answer with server-sent events (data: {...}).
    sed -n 's/^data:[[:space:]]*//p' "${file}" \
        | while IFS= read -r line; do
            if printf '%s' "${line}" | jq -e . >/dev/null 2>&1; then
                printf '%s\n' "${line}"
            fi
        done \
        | tail -n 1
}

# Probe the MCP endpoint with the configured bearer token. Prints a concise
# summary and returns non-zero if the endpoint is not callable.
mcp_probe() {
    local token="$1"
    (
        set -euo pipefail
        local tmpdir headers init_body init_json session_id tools_body tools_json tool_count unauth_code
        tmpdir="$(mktemp -d)"
        trap 'rm -rf "${tmpdir}"' EXIT

        headers="${tmpdir}/headers"
        init_body="${tmpdir}/init.json"
        tools_body="${tmpdir}/tools.json"
        local -a session_header=()

        unauth_code="$(http_code "${MCP_URL}" \
            -H 'Content-Type: application/json' \
            -H 'Accept: application/json, text/event-stream' \
            -d '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"reverse-pi-check","version":"1.0"}}}')"

        if [[ "${unauth_code}" != "401" && "${unauth_code}" != "403" ]]; then
            warn "unauthenticated /mcp returned HTTP ${unauth_code}, expected 401/403"
        fi

        curl -sS --max-time 15 \
            -D "${headers}" \
            -o "${init_body}" \
            -H "Authorization: Bearer ${token}" \
            -H 'Content-Type: application/json' \
            -H 'Accept: application/json, text/event-stream' \
            -d '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"reverse-pi-check","version":"1.0"}}}' \
            "${MCP_URL}" || return 1

        init_json="$(_extract_mcp_json "${init_body}")"
        if [[ -z "${init_json}" ]] || ! printf '%s' "${init_json}" | jq -e '.result' >/dev/null 2>&1; then
            echo "MCP initialize failed: $(tr '\n' ' ' <"${init_body}" | head -c 500)" >&2
            return 1
        fi

        session_id="$(grep -i '^mcp-session-id:' "${headers}" | tail -n 1 | cut -d: -f2- | tr -d ' \r' || true)"
        if [[ -n "${session_id}" ]]; then
            session_header=(-H "Mcp-Session-Id: ${session_id}")
            curl -sS --max-time 10 \
                -o /dev/null \
                -H "Authorization: Bearer ${token}" \
                "${session_header[@]}" \
                -H 'Content-Type: application/json' \
                -H 'Accept: application/json, text/event-stream' \
                -d '{"jsonrpc":"2.0","method":"notifications/initialized"}' \
                "${MCP_URL}" || true
        fi

        curl -sS --max-time 15 \
            -o "${tools_body}" \
            -H "Authorization: Bearer ${token}" \
            "${session_header[@]}" \
            -H 'Content-Type: application/json' \
            -H 'Accept: application/json, text/event-stream' \
            -d '{"jsonrpc":"2.0","id":2,"method":"tools/list","params":{}}' \
            "${MCP_URL}" || return 1

        tools_json="$(_extract_mcp_json "${tools_body}")"
        if [[ -z "${tools_json}" ]] || ! printf '%s' "${tools_json}" | jq -e '.result.tools' >/dev/null 2>&1; then
            echo "MCP tools/list failed: $(tr '\n' ' ' <"${tools_body}" | head -c 500)" >&2
            return 1
        fi

        tool_count="$(printf '%s' "${tools_json}" | jq -r '.result.tools | length')"
        if [[ "${tool_count}" -lt 1 ]]; then
            echo "MCP tools/list returned no tools." >&2
            return 1
        fi

        printf 'MCP endpoint: %s\n' "${MCP_URL}"
        printf 'Unauthenticated probe: HTTP %s\n' "${unauth_code}"
        printf 'Authenticated tools/list: %s tool(s)\n' "${tool_count}"
    )
}

container_state() {
    docker inspect -f '{{.State.Status}}' "${CONTAINER_NAME}" 2>/dev/null || printf 'missing'
}

container_health() {
    docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "${CONTAINER_NAME}" 2>/dev/null || printf 'unknown'
}

platform_string() {
    docker version --format '{{.Server.Os}}/{{.Server.Arch}}' 2>/dev/null || printf 'linux/amd64'
}

# Strip the digest and tag while keeping a registry port (host:5000/name).
image_repository() {
    local ref="${1:-${IMAGE}}"
    ref="${ref%%@*}"
    if [[ "${ref##*/}" == *:* ]]; then
        ref="${ref%:*}"
    fi
    printf '%s' "${ref}"
}

# Split an image reference into "<registry> <repository>".
split_image_ref() {
    local ref="$1" first rest registry repo
    ref="${ref%%@*}"
    if [[ "${ref}" == */* ]]; then
        first="${ref%%/*}"
        rest="${ref#*/}"
        if [[ "${first}" == *.* || "${first}" == *:* || "${first}" == "localhost" ]]; then
            registry="${first}"
            repo="${rest}"
        else
            registry="docker.io"
            repo="${ref}"
        fi
    else
        registry="docker.io"
        repo="library/${ref}"
    fi
    if [[ "${repo##*/}" == *:* ]]; then
        repo="${repo%:*}"
    fi
    printf '%s %s' "${registry}" "${repo}"
}

# Top-level digest of a tag (image index or single manifest). This matches the
# digest Docker records in RepoDigests, so it can be compared with the local
# image without pulling.
remote_image_digest() {
    local ref="$1"
    if [[ "${ref}" == *"@"* ]]; then
        printf '%s' "${ref##*@}"
        return 0
    fi

    local registry repo tag token_url api token digest
    read -r registry repo <<<"$(split_image_ref "${ref}")"
    tag="latest"
    if [[ "${ref##*/}" == *:* ]]; then
        tag="${ref##*:}"
    fi

    case "${registry}" in
        docker.io|index.docker.io)
            api="https://registry-1.docker.io"
            token_url="https://auth.docker.io/token?service=registry.docker.io&scope=repository:${repo}:pull"
            ;;
        *)
            api="https://${registry}"
            token_url="https://${registry}/token?scope=repository:${repo}:pull&service=${registry}"
            ;;
    esac

    token="$(curl -fsS --max-time 15 "${token_url}" 2>/dev/null | jq -r '.token // .access_token // empty' 2>/dev/null || true)"
    local -a auth=()
    if [[ -n "${token}" ]]; then
        auth=(-H "Authorization: Bearer ${token}")
    fi
    digest="$(curl -fsSI --max-time 15 \
        "${auth[@]}" \
        -H 'Accept: application/vnd.oci.image.index.v1+json, application/vnd.docker.distribution.manifest.list.v2+json, application/vnd.oci.image.manifest.v1+json, application/vnd.docker.distribution.manifest.v2+json' \
        "${api}/v2/${repo}/manifests/${tag}" 2>/dev/null \
        | tr -d '\r' \
        | awk 'tolower($1) == "docker-content-digest:" {print $2}' \
        | tail -n 1)"
    [[ -n "${digest}" ]] || return 1
    printf '%s' "${digest}"
}

local_image_digest() {
    local ref="$1" repo digests
    repo="$(image_repository "${ref}")"
    digests="$(docker image inspect --format '{{json .RepoDigests}}' "${ref}" 2>/dev/null || true)"
    [[ -n "${digests}" ]] || return 0
    jq -r --arg prefix "${repo}@" '
        first(.[] | select(startswith($prefix))) // empty
    ' <<<"${digests}" 2>/dev/null | sed 's/^[^@]*@//' || true
}

local_image_id() {
    docker image inspect --format '{{.Id}}' "$1" 2>/dev/null || true
}

container_image_id() {
    docker inspect --format '{{.Image}}' "${CONTAINER_NAME}" 2>/dev/null || true
}
